export function normalizeAnswerStyle(raw?: string): AnswerStyle {
  if (raw === "Detailed Explanation (In-Depth Human Answer)") {
    return "Detailed Explanation (In-Depth Human Answer)";
  }
  return "Point-to-Point (Direct Human Answer)";
}

export function normalizeProgrammingLanguage(raw?: string): ProgrammingLanguage {
  if (
    raw &&
    (PROGRAMMING_LANGUAGES as readonly string[]).includes(raw)
  ) {
    return raw as ProgrammingLanguage;
  }
  return "Python";
}

