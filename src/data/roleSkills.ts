export function getSuggestedSkillsForRole(role: string): readonly string[] {
  return ROLE_SKILLS_MAP[role] || ROLE_SKILLS_MAP[CUSTOM_ROLE_OPTION];
}

export function parseSkillsCsv(csv: string): string[] {
  const seen = new Set<string>();
  const result: string[] = [];
  for (const raw of csv.split(",")) {
    const clean = raw.trim();
    if (!clean) continue;
    const key = clean.toLowerCase();
    if (!seen.has(key)) {
      seen.add(key);
      result.push(clean);
    }
  }
  return result;
}

export function toggleSkillInCsv(csv: string, skill: string): string {
  const current = parseSkillsCsv(csv);
  const targetLower = skill.trim().toLowerCase();
  const exists = current.some((s) => s.toLowerCase() === targetLower);
  const next = exists
    ? current.filter((s) => s.toLowerCase() !== targetLower)
    : [...current, skill.trim()];
  return next.join(", ");
}

export function hasSkillInCsv(csv: string, skill: string): boolean {
  const targetLower = skill.trim().toLowerCase();
  return parseSkillsCsv(csv).some((s) => s.toLowerCase() === targetLower);
}
